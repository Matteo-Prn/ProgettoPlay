package com.play.util.validation;

/**
 * Enum che rappresenta i campi di validazione per una domanda e risposte.
 * Utilizzato per identificare i diversi elementi da validare
 * all'interno di una domanda di esercizio.
 */
public enum QuestionValidationField {
    QUESTION_TEXT,
    ANSWER_A,
    ANSWER_B,
    ANSWER_C,
    ANSWER_D,
    NO_CORRECT_ANSWER_SELECTED;
}
